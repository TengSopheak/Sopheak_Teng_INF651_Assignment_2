// 1. Variables and Data Types
let personName = "Sopheak Teng";
var age = 21;
const isStudent = true;

console.log("Name:", personName);
console.log("Age:", age);
console.log("Is Student:", isStudent);

// 2. Basic Arithmetic Operations
let num1 = 10;
let num2 = 5;

var addition = num1 + num2;
var subtraction = num1 - num2;
var multiplication = num1 * num2;
var division = num1 / num2;

console.log("Addition:", addition);
console.log("Subtraction:", subtraction);
console.log("Multiplication:", multiplication);
console.log("Division:", division);

// 3. Working with Strings
const greeting = "Well, hello there!";

console.log("Length of greeting:", greeting.length);
console.log("First character of greeting:", greeting.charAt(0));
console.log("Last character of greeting:", greeting.charAt(greeting.length - 1));

// 4. Math Object
var negNumber = -14;

var squareRoot = Math.sqrt(negNumber);
var numSquared = Math.pow(negNumber, 2);
var absoluteValue = Math.abs(negNumber);

console.log("Square Root:", squareRoot);
console.log("Number Squared:", numSquared);
console.log("Absolute Value:", absoluteValue);

// 5. Boolean Logic and Comparison Operators
var nNum1 = 14;
var nNum2 = 7;

console.log("Is nNum1 greater than nNum2?", nNum1 > nNum2);
console.log("Is nNum1 less than nNum2?", nNum1 < nNum2);
console.log("Is nNum1 equal to nNum2?", nNum1 === nNum2);

// 6. Logical Operators
let boolean1 = true;
let boolean2 = false;

console.log("boolean1 AND boolean2:", boolean1 && boolean2);
console.log("boolean1 OR boolean2:", boolean1 || boolean2);
console.log("NOT boolean1:", !boolean1);
console.log("NOT boolean2:", !boolean2);